def selftest() -> dict[str, Any]:
    """Run the compiled self-test of the kernels (src/selftest.cpp).

    Returns
    -------
    ``n`` (checks run), ``nfail`` (checks failed) and ``report`` (one line
    per failed check; empty when all pass).

    Examples
    --------
    >>> r = selftest()
    >>> r["nfail"], r["report"]
    (0, '')
    """
    return _clab.selftest()
