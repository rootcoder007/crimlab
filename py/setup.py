"""The build of crimlab for Python.

In the repository the kernels are compiled from ../src: every .cpp and .h
there that does not include R's headers (the R binding) is copied to
ext/k before each build, together with the version from ../DESCRIPTION,
the proof table of the R binding, the Lean files and the licence. These
copies are build output, never edited or committed; an sdist carries them,
so it builds on its own.
"""

import re
import shutil
from pathlib import Path

from setuptools import Extension, setup
from setuptools.command.build_ext import build_ext

here = Path(__file__).resolve().parent
top = here.parent
pkg = here / "crimlab"
R = re.compile(r'#\s*include\s*[<"](R\.h|Rinternals\.h|Rmath\.h|R_ext/[^>"]*|rchk\.h)[>"]')


def sync():
    src = top / "src"
    if not (src / "crimlab.h").is_file():
        return  # an sdist: the copies are here already
    k = here / "ext" / "k"
    shutil.rmtree(k, ignore_errors=True)
    k.mkdir(parents=True)
    for f in sorted(src.iterdir()):
        if f.suffix in (".cpp", ".h") and not R.search(f.read_text(encoding="utf-8")):
            shutil.copy2(f, k / f.name)
    desc = (top / "DESCRIPTION").read_text(encoding="utf-8")
    ver = re.search(r"^Version:\s*(\S+)", desc, re.MULTILINE).group(1).replace("-", ".")
    (pkg / "_version.py").write_text(f'__version__ = "{ver}"\n', encoding="utf-8")
    bind = (src / "bind.cpp").read_text(encoding="utf-8")
    block = re.search(r"const Thm thms\[\] = \{(.*?)\n\};", bind, re.DOTALL).group(1)
    rows = re.findall(r'\{"(\w+)", "(\w+)", "(\w+)"\}', block)
    (pkg / "_thm.py").write_text(
        "# Generated by setup.py from src/bind.cpp: do not edit.\n"
        "THM: tuple[tuple[str, str, str], ...] = (\n" + "".join(f"    {r!r},\n" for r in rows) + ")\n",
        encoding="utf-8",
    )
    lean = pkg / "lean"
    shutil.rmtree(lean, ignore_errors=True)
    lean.mkdir()
    for f in sorted((top / "inst" / "lean").glob("*.lean")):
        shutil.copy2(f, lean / f.name)
    for f in ("LICENSE", "NOTICE"):
        shutil.copy2(top / f, here / f)


class Build(build_ext):
    """C++17 on every compiler; warnings shown (CI adds -Werror or /WX)."""

    def build_extensions(self):
        msvc = self.compiler.compiler_type == "msvc"
        flags = ["/std:c++17", "/EHsc", "/W3"] if msvc else ["-std=c++17", "-Wall", "-Wextra"]
        for e in self.extensions:
            e.extra_compile_args = flags
        super().build_extensions()


sync()
version = re.search(r'"(.+)"', (pkg / "_version.py").read_text(encoding="utf-8")).group(1)
setup(
    version=version,
    ext_modules=[
        Extension(
            "crimlab._clab",
            sources=["ext/clab.cpp"] + sorted(f"ext/k/{f.name}" for f in (here / "ext" / "k").glob("*.cpp")),
            include_dirs=["ext/k"],
            define_macros=[("Py_LIMITED_API", "0x030A0000")],
            py_limited_api=True,
            language="c++",
        )
    ],
    cmdclass={"build_ext": Build},
    options={"bdist_wheel": {"py_limited_api": "cp310"}},
)
