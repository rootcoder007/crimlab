test_that("olsdx() agrees with lm() and its influence measures", {
  set.seed(4)
  n <- 84
  w <- data.frame(temp = rnorm(n, 26, 8), hum = runif(n, 10, 60),
                  haze = rpois(n, 15))
  y <- 5 + 0.7 * w$temp + 0.15 * w$hum + 0.35 * w$haze + rnorm(n, sd = 4)
  r <- olsdx(y, w, level = 0.9)
  f <- lm(y ~ temp + hum + haze, data = w)
  s <- summary(f)
  expect_s3_class(r, "olsdx")
  expect_identical(r$coef$term, c("(Intercept)", "temp", "hum", "haze"))
  expect_equal(r$coef$est, unname(coef(f)), tolerance = 1e-10)
  expect_equal(r$coef$se, unname(s$coefficients[, 2]), tolerance = 1e-10)
  expect_equal(r$coef$t, unname(s$coefficients[, 3]), tolerance = 1e-10)
  expect_equal(r$coef$p, unname(s$coefficients[, 4]), tolerance = 1e-8)
  ci <- confint(f, level = 0.9)
  expect_equal(r$coef$lo, unname(ci[, 1]), tolerance = 1e-10)
  expect_equal(r$coef$hi, unname(ci[, 2]), tolerance = 1e-10)
  # standardised coefficients and variance inflation, by hand
  x <- as.matrix(w)
  expect_equal(r$coef$beta[-1], unname(coef(f)[-1] * apply(x, 2, sd) / sd(y)),
               tolerance = 1e-10)
  vif <- vapply(colnames(x), function(k) {
    1 / (1 - summary(lm(x[, k] ~ x[, colnames(x) != k]))$r.squared)
  }, 0)
  expect_equal(r$coef$vif[-1], unname(vif), tolerance = 1e-10)
  expect_equal(r$coef$tol[-1], unname(1 / vif), tolerance = 1e-10)
  expect_true(all(is.na(r$coef[1, c("beta", "tol", "vif")])))
  expect_equal(r$cor, unname(cor(x)), tolerance = 1e-12)
  # the fit
  e <- residuals(f)
  expect_equal(r$fit$r2, s$r.squared, tolerance = 1e-12)
  expect_equal(r$fit$r, sqrt(s$r.squared), tolerance = 1e-12)
  expect_equal(r$fit$adjr2, s$adj.r.squared, tolerance = 1e-12)
  expect_equal(r$fit$sigma, s$sigma, tolerance = 1e-12)
  expect_equal(r$fit$f, unname(s$fstatistic[1]), tolerance = 1e-10)
  expect_identical(c(r$fit$df1, r$fit$df2, r$fit$n, r$fit$k),
                   c(3, n - 4, n, 4))
  expect_equal(r$fit$p, pf(s$fstatistic[1], 3, n - 4, lower.tail = FALSE),
               tolerance = 1e-8, ignore_attr = TRUE)
  expect_equal(r$fit$dw, sum(diff(e)^2) / sum(e^2), tolerance = 1e-12)
  expect_equal(r$fit$rss, sum(e^2), tolerance = 1e-12)
  expect_equal(r$vcov, unname(vcov(f)), tolerance = 1e-10)
  # the rows
  cs <- r$cases
  expect_equal(cs$fit, unname(fitted(f)), tolerance = 1e-12)
  expect_equal(cs$resid, unname(e), tolerance = 1e-10)
  expect_equal(cs$zres, unname(e / s$sigma), tolerance = 1e-10)
  expect_equal(cs$sres, unname(rstandard(f)), tolerance = 1e-10)
  expect_equal(cs$tres, unname(rstudent(f)), tolerance = 1e-10)
  expect_equal(cs$hat, unname(hatvalues(f)), tolerance = 1e-10)
  expect_equal(cs$cook, unname(cooks.distance(f)), tolerance = 1e-10)
  expect_null(r$pred)
  expect_identical(r$ptype, "mean")
  expect_true(r$int)
})

test_that("olsdx() predicts the mean and a new row as predict() does", {
  set.seed(5)
  w <- data.frame(temp = rnorm(60, 30, 6), hum = runif(60, 20, 80),
                  haze = rpois(60, 10))
  y <- 3 + 0.5 * w$temp + 0.2 * w$hum + 0.4 * w$haze + rnorm(60, sd = 3)
  f <- lm(y ~ temp + hum + haze, data = w)
  nd <- data.frame(temp = c(35, 20), hum = c(74, 40), haze = c(25, 5))
  m <- olsdx(y, w, at = nd)$pred
  pm <- predict(f, nd, interval = "confidence", se.fit = TRUE)
  expect_equal(m$fit, unname(pm$fit[, "fit"]), tolerance = 1e-10)
  expect_equal(m$se, unname(pm$se.fit), tolerance = 1e-10)
  expect_equal(m$lo, unname(pm$fit[, "lwr"]), tolerance = 1e-10)
  expect_equal(m$hi, unname(pm$fit[, "upr"]), tolerance = 1e-10)
  p <- olsdx(y, w, at = nd, pred = "new", level = 0.8)
  pp <- predict(f, nd, interval = "prediction", level = 0.8)
  expect_equal(p$pred$lo, unname(pp[, "lwr"]), tolerance = 1e-10)
  expect_equal(p$pred$hi, unname(pp[, "upr"]), tolerance = 1e-10)
  expect_identical(p$ptype, "new")
  # one point as a vector, named or not, and a matrix
  v <- olsdx(y, w, at = c(temp = 35, hum = 74, haze = 25))$pred
  expect_equal(v, m[1, ], ignore_attr = TRUE)
  expect_identical(olsdx(y, w, at = c(35, 74, 25))$pred, v)
  expect_identical(olsdx(y, as.matrix(w), at = as.matrix(nd))$pred, m)
})

test_that("olsdx() by hand, and without the constant", {
  # y = 1 3 2 5 on x = 0 1 2 3: b = 1.1 and 1.1, RSS 2.7, TSS 8.75
  r <- olsdx(c(1, 3, 2, 5), 0:3, at = 2)
  expect_equal(r$coef$est, c(1.1, 1.1), tolerance = 1e-12)
  expect_equal(r$fit$r2, 1 - 2.7 / 8.75, tolerance = 1e-12)
  expect_equal(r$fit$dw, 8.83 / 2.7, tolerance = 1e-12)
  expect_equal(r$cases$hat, c(0.7, 0.3, 0.3, 0.7), tolerance = 1e-12)
  expect_equal(r$pred$se, sqrt(1.35 * 0.3), tolerance = 1e-12)
  expect_identical(r$coef$term, c("(Intercept)", "x1"))
  set.seed(6)
  x <- cbind(a = runif(30), b = runif(30))
  y <- 2 * x[, 1] - x[, 2] + rnorm(30, sd = 0.3)
  r0 <- olsdx(y, x, int = FALSE)
  f0 <- lm(y ~ 0 + x)
  s0 <- summary(f0)
  expect_identical(r0$coef$term, c("a", "b"))
  expect_false(r0$int)
  expect_equal(r0$coef$se, unname(s0$coefficients[, 2]), tolerance = 1e-10)
  expect_equal(r0$fit$r2, s0$r.squared, tolerance = 1e-12)
  expect_equal(r0$fit$adjr2, s0$adj.r.squared, tolerance = 1e-12)
  expect_equal(r0$fit$f, unname(s0$fstatistic[1]), tolerance = 1e-10)
  expect_equal(r0$cases$cook, unname(cooks.distance(f0)), tolerance = 1e-10)
})

test_that("olsdx() refuses what it cannot fit", {
  y <- c(1, 3, 2, 5, 4)
  x <- c(0, 1, 2, 3, 5)
  expect_error(olsdx(y, x, pred = "best"), "`pred` must be one of")
  expect_error(olsdx(y, x, level = 1), "`level` must be one number")
  expect_error(olsdx(y, x, int = NA), "`int` must be TRUE or FALSE")
  expect_error(olsdx(c(1, NA, 2, 5, 4), x), "`y` must be finite numbers")
  expect_error(olsdx(y, x[-1]), "`x` must have one row per row of `y`, 5")
  expect_error(olsdx(y[1:3], x[1:3]), "`y` must have at least 4 values")
  expect_error(olsdx(rep(2, 5), x), "`y` is constant")
  expect_error(olsdx(y, cbind(x, 2 * x)), "the columns of `x` are collinear")
  expect_error(olsdx(y, rep(1, 5)), "collinear \\(with the constant\\)")
  expect_error(olsdx(2 * x + 1, x), "the fit is exact")
  expect_error(olsdx(y, x, at = matrix(1, 1, 2)),
               "`at` must be a numeric matrix with the 1 columns of `x`")
  expect_error(olsdx(y, x, at = "a"), "`at` must be a numeric matrix")
  expect_error(olsdx(y, cbind(t = x), at = c(h = 1)),
               "`at` must name its columns as `x` does, in its order: t")
  expect_error(olsdx(y, x, at = NA_real_), "`at` must be finite numbers")
  r <- olsdx(y, x)
  expect_error(print(r, lev = 0.2), "`lev` two increasing numbers")
  expect_error(print(r, cook = "1"), "must be one number each")
  expect_output(print(r), "olsdx: 5 rows, 2 coefficients")
  expect_output(print(olsdx(y, x, at = 2)), "means at `at`")
})
